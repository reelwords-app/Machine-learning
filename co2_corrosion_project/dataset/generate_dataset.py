"""
Physics-based CO2 corrosion-rate dataset generator for CO2 transport pipelines.

IMPORTANT - DATA PROVENANCE
---------------------------
This dataset is NOT a collection of raw experimental measurements scraped from
papers (no automated tool in this environment could fetch full paywalled-paper
text). Instead, it is generated by sampling realistic pipeline operating
conditions (ranges reported across the literature reviewed in
references/references.csv) and evaluating them with PUBLISHED, CITABLE
empirical CO2 corrosion-rate correlations:

  1. de Waard-Milliams (1975/1993) base correlation
     log10(Vcorr) = 5.8 - 1710/T + 0.67*log10(pCO2)
     Vcorr in mm/year, T in Kelvin, pCO2 in bar (CO2 partial pressure / fugacity)
     Cited in: R017, R018, R020-R023 (references.csv)

  2. de Waard (1995) update with an explicit pH-correction term
     log10(Vcorr) = 4.93 - 1119/T + 0.58*log10(pCO2) - 0.34*(pH_real - pH_CO2sat)
     Cited in: R020 (references.csv); widely reproduced in pipeline-engineering
     handbooks (R017, R021-R023)

  3. Shear-stress flow-sensitivity correlation (NORSOK-family / RCE studies)
     CR_flow = CR_base * (tau_w / tau_ref)^0.8
     of the documented form  R_COR = a * tau_w^b  (Nesic / RCE flow studies)
     Cited in: R064 (references.csv)

These equations are real, peer-reviewed, citable correlations - the values
computed are MODEL-DERIVED, not experimental observations. Gaussian noise is
added to emulate the scatter reported between replicate experiments and
between competing models in the literature (see README.md for full discussion
of this design choice and its limitations).
"""

import csv
import math
import random

random.seed(42)

N_SAMPLES = 6000

# Realistic operating-condition ranges, drawn from ranges reported across the
# papers catalogued in references.csv (e.g. R024-R028 NORSOK validity range,
# R039/R006 CCS dense-phase ranges, R153 elevated P/T experiments).
T_RANGE_C = (5, 150)          # temperature, degrees C   (NORSOK validity: 5-150 C)
PCO2_RANGE_BAR = (0.1, 100)   # CO2 partial pressure/fugacity, bar
                              # (0.1-10 bar = NORSOK range; up to ~100 bar covers
                              #  dense-phase / CCS transport conditions, R006/R039)
PH_RANGE = (3.5, 6.5)         # NORSOK validity range (R024-R028)
SHEAR_RANGE_PA = (1, 150)     # wall shear stress, Pa (NORSOK validity range)
CL_RANGE_WT = (0.0, 20.0)     # NaCl concentration, wt% (R109-R115)


def pH_co2_saturated(T_K, pCO2_bar):
    """Approximate pH of pure water in equilibrium with CO2 at given T, pCO2.
    Simplified relation consistent with the trend reported in de Waard-type
    models (lower pH at higher pCO2 / lower temperature)."""
    return 3.82 + 0.00384 * (T_K - 293.0) - 0.27 * math.log10(max(pCO2_bar, 1e-3))


def dewaard_milliams_1975(T_C, pCO2_bar):
    """Base de Waard-Milliams (1975) correlation. Returns mm/year."""
    T_K = T_C + 273.15
    log_v = 5.8 - 1710.0 / T_K + 0.67 * math.log10(pCO2_bar)
    return 10 ** log_v


def dewaard_1995(T_C, pCO2_bar, pH_actual):
    """de Waard (1995) correlation with explicit pH correction. Returns mm/year."""
    T_K = T_C + 273.15
    pH_sat = pH_co2_saturated(T_K, pCO2_bar)
    log_v = 4.93 - 1119.0 / T_K + 0.58 * math.log10(pCO2_bar) - 0.34 * (pH_actual - pH_sat)
    return 10 ** log_v


def flow_correction(base_rate, shear_pa, shear_ref_pa=10.0, exponent=0.8):
    """Shear-stress flow-sensitivity scaling, of the documented R_COR = a*tau^b
    form reported in rotating-cylinder-electrode flow studies (R064)."""
    return base_rate * (shear_pa / shear_ref_pa) ** exponent


def salinity_correction(rate, cl_wt_pct):
    """High salinity suppresses CO2 corrosion via reduced CO2 solubility
    ('salting-out'), as reported in R109-R115. Simplified monotonic damping."""
    return rate * (1.0 - 0.45 * (cl_wt_pct / 20.0))


def generate_row(rng):
    T_C = rng.uniform(*T_RANGE_C)
    pCO2 = 10 ** rng.uniform(math.log10(PCO2_RANGE_BAR[0]), math.log10(PCO2_RANGE_BAR[1]))
    pH = rng.uniform(*PH_RANGE)
    shear = 10 ** rng.uniform(math.log10(SHEAR_RANGE_PA[0]), math.log10(SHEAR_RANGE_PA[1]))
    cl_wt = rng.uniform(*CL_RANGE_WT)

    base_dw1975 = dewaard_milliams_1975(T_C, pCO2)
    base_dw1995 = dewaard_1995(T_C, pCO2, pH)

    rate_dw1975 = salinity_correction(flow_correction(base_dw1975, shear), cl_wt)
    rate_dw1995 = salinity_correction(flow_correction(base_dw1995, shear), cl_wt)

    # Multiplicative log-normal noise to emulate inter-laboratory / inter-model
    # scatter reported in the literature (typically a factor of ~1.3-2x, e.g.
    # discussed in R009, R039, R075).
    noise_dw1975 = math.exp(rng.gauss(0, 0.18))
    noise_dw1995 = math.exp(rng.gauss(0, 0.18))

    rate_dw1975 *= noise_dw1975
    rate_dw1995 *= noise_dw1995

    # "Consensus" target = geometric mean of the two model families - this is
    # the prediction target the ML model below is trained against, deliberately
    # framed as "can ML reconcile/interpolate between competing published
    # empirical models" (see paper/ for the research-gap framing).
    target = math.sqrt(rate_dw1975 * rate_dw1995)

    return {
        "temperature_C": round(T_C, 2),
        "pCO2_bar": round(pCO2, 4),
        "pH": round(pH, 2),
        "wall_shear_stress_Pa": round(shear, 3),
        "NaCl_wt_pct": round(cl_wt, 2),
        "corrosion_rate_dewaard1975_mmpy": round(rate_dw1975, 5),
        "corrosion_rate_dewaard1995_mmpy": round(rate_dw1995, 5),
        "corrosion_rate_target_mmpy": round(target, 5),
        "model_disagreement_ratio": round(max(rate_dw1975, rate_dw1995) /
                                           max(min(rate_dw1975, rate_dw1995), 1e-9), 4),
        "regime": classify_regime(T_C, pCO2),
        # --- Per-row provenance: which published, citable equation produced
        # each value (reference IDs match references/references.csv). This
        # dataset is MODEL-DERIVED from these cited correlations, not raw
        # experimental measurements -- see dataset/README.md and the paper's
        # "Dataset Construction (Transparency Statement)" section.
        "source_dewaard1975_refs": "R017;R018;R020;R021;R022;R023",
        "source_dewaard1995_refs": "R020",
        "source_flow_correction_refs": "R064",
        "source_salinity_correction_refs": "R109;R110;R111;R112;R113;R114;R115",
        "source_operating_ranges_refs": "R024;R025;R026;R027;R028;R006;R039",
    }


def classify_regime(T_C, pCO2_bar):
    """Tag each sample with its CO2 phase / transport regime, since model
    disagreement concentrates in the dense-phase / CCS-relevant regime
    (research gap discussed in R006, R039, R006)."""
    if pCO2_bar > 73.8 and T_C < 31:
        return "dense_phase_liquid_CO2"
    elif pCO2_bar > 73.8:
        return "dense_phase_supercritical_CO2"
    elif pCO2_bar > 10:
        return "high_pressure_gas_CO2"
    else:
        return "conventional_oilfield_range"


def main():
    rng = random.Random(42)
    rows = [generate_row(rng) for _ in range(N_SAMPLES)]

    fieldnames = list(rows[0].keys())
    out_path = "co2_corrosion_dataset.csv"
    with open(out_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Wrote {len(rows)} rows to {out_path}")
    regimes = {}
    for r in rows:
        regimes[r["regime"]] = regimes.get(r["regime"], 0) + 1
    print("Regime distribution:", regimes)


if __name__ == "__main__":
    main()
